"""Writes docs/PYTHON_PACKAGES.md: every package in uv.lock, its version, its licence as its own
metadata states it, what it is needed for, and whether it can load into Wavescribe's process.

    uv sync --offline
    uv run --offline python scripts/licence_table.py            # write the page
    uv run --offline python scripts/licence_table.py --check    # exit 1 if the page is stale

Run it with the project's environment after uv.lock changes: the licences come from the
installed packages, so the environment must match the lock. The commit checks hold the page to
uv.lock by name and version (`scripts/commit_checks.py`).

"In-process" is measured, not declared: a fresh interpreter imports every Wavescribe module,
every module Wavescribe's sources import anywhere (also inside functions), and the model loaders
the model libraries call when weights load; a package is "yes" when one of its modules is then
loaded.
"""

from __future__ import annotations

import ast
import importlib.metadata as md
import json
import platform
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HERE = {"Darwin": "macOS", "Linux": "Linux", "Windows": "Windows"}.get(
    platform.system(), "this system"
)
PAGE = ROOT / "docs" / "PYTHON_PACKAGES.md"
SOURCES = ROOT / "src" / "wavescribe"
# What the model libraries import when weights load, which importing their top modules doesn't
# reach: Whisper's processor (mlx-audio), the mel filterbank (parakeet-mlx), the LiteRT
# interpreter (YAMNet).
MODEL_LOADERS = (
    "parakeet_mlx", "mlx_lm", "mlx_audio.stt", "ctranslate2", "sentencepiece", "onnxruntime",
    "ai_edge_litert.interpreter", "librosa.filters",
    "transformers.models.whisper.feature_extraction_whisper",
    "transformers.models.whisper.processing_whisper",
)  # fmt: skip

HEAD = """\
# Python packages

Every Python package in `uv.lock`, the file that pins what `uv sync` installs. This page is
generated by `scripts/licence_table.py` from `uv.lock` and the installed packages' metadata;
don't edit it by hand. A commit that changes one without the other is refused by the commit
checks.

- **Licence:** as the package's own metadata states it: its SPDX expression, its short License
  field, or its licence classifiers. [LICENSING.md](LICENSING.md) has the reviewed licences of
  the dependencies Wavescribe names and how it uses them; it wins where the two differ.
- **Needed for:** *running* when Wavescribe needs it, directly or through another package;
  *development* when only the tests and the lint need it. A package that only some platforms
  install says where, in uv's own terms (`sys_platform == 'darwin'` is macOS).
- **In-process:** *yes* when importing Wavescribe's modules, the modules its code imports, or the
  model loaders its model libraries call loads it into Wavescribe's own process. Some load only
  on one path, which LICENSING.md says. *No* when none of those loads it: it is installed with
  another package and not imported on those paths.

| Package | Version | Licence | Needed for | In-process |
|---|---|---|---|---|
"""


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def atoms(marker: str | None) -> frozenset[str]:
    """A marker's conditions that must all hold; one with an `or` stays whole."""
    if not marker:
        return frozenset()
    if " or " in marker:
        return frozenset({f"({marker})"})
    return frozenset(part.strip() for part in marker.split(" and "))


def locked(lock: dict) -> tuple[list[dict], dict[str, str], dict[str, str]]:
    """The locked packages (without Wavescribe itself), what each is needed for, and, for one
    that only some platforms install, the condition under which they do."""
    packages = {p["name"]: p for p in lock["package"]}
    root = next(p for p in lock["package"] if p.get("source", {}).get("editable"))
    starts = [("running", e) for e in root.get("dependencies", [])]
    starts += [("development", e) for g in root.get("dev-dependencies", {}).values() for e in g]
    # A path's condition is every marker met along it; a package is installed wherever one of
    # its paths' conditions holds, so only the weakest conditions count.
    reached: dict[str, dict[str, set[frozenset[str]]]] = {}
    todo = [(purpose, e["name"], atoms(e.get("marker"))) for purpose, e in starts]
    while todo:
        purpose, name, condition = todo.pop()
        seen = reached.setdefault(name, {}).setdefault(purpose, set())
        if any(c <= condition for c in seen):
            continue
        seen.add(condition)
        for e in packages[name].get("dependencies", []):
            todo.append((purpose, e["name"], condition | atoms(e.get("marker"))))
    need, only = {}, {}
    for name, by in reached.items():
        purpose = "running" if "running" in by else "development"
        need[name] = purpose
        weakest = {c for c in by[purpose] if not any(o < c for o in by[purpose])}
        if frozenset() not in weakest:
            only[name] = " or ".join(sorted(" and ".join(sorted(c)) for c in weakest))
    rest = sorted((p for p in lock["package"] if p is not root), key=lambda p: norm(p["name"]))
    return rest, need, only


def licence(dist: md.Distribution) -> str:
    meta = dist.metadata
    if expression := meta.get("License-Expression"):
        return expression.strip()
    field = (meta.get("License") or "").strip()
    if field and len(field) <= 80 and "\n" not in field:
        return field
    classifiers = [
        c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")
    ]
    return "; ".join(classifiers) or ("in the licence text" if field else "not stated")


def imported_by_sources() -> list[str]:
    """Every module Wavescribe's sources import, at any depth, other than its own."""
    found: set[str] = set()
    for path in sorted(SOURCES.rglob("*.py")):
        for node in ast.walk(ast.parse(path.read_text(), str(path))):
            if isinstance(node, ast.Import):
                found |= {alias.name for alias in node.names}
            elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
                found.add(node.module)
                found |= {f"{node.module}.{alias.name}" for alias in node.names}
    return sorted(m for m in found if m.split(".")[0] != "wavescribe")


PROBE = """
import importlib, importlib.metadata as md, json, pkgutil, sys, warnings
warnings.simplefilter("ignore")
import wavescribe
names = [m.name for m in pkgutil.walk_packages(wavescribe.__path__, "wavescribe.")]
names = [n for n in names if not n.endswith("__main__")] + json.loads(sys.argv[1])
for name in names:
    try:
        importlib.import_module(name)
    except Exception:
        pass  # a name that is a function, not a module, or a part that isn't installed here
owners = md.packages_distributions()
print(json.dumps(sorted({d for m in list(sys.modules) for d in owners.get(m.split(".")[0], [])})))
"""


def loaded() -> set[str]:
    """Distributions with a module loaded once everything Wavescribe can import is imported."""
    wanted = imported_by_sources() + list(MODEL_LOADERS)
    out = subprocess.run(
        [sys.executable, "-c", PROBE, json.dumps(wanted)],
        capture_output=True, text=True, timeout=600, check=True, cwd=ROOT,
    )  # fmt: skip
    return {norm(d) for d in json.loads(out.stdout.strip().splitlines()[-1])}


def page() -> str:
    lock = tomllib.loads((ROOT / "uv.lock").read_text())
    packages, need, marker = locked(lock)
    in_process = loaded()
    rows = []
    stale = []
    for p in packages:
        name, version = p["name"], p["version"]
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            dist = None
        if dist is not None and dist.version != version:
            stale.append(f"{name} {dist.version} installed, {version} locked")
        text = licence(dist) if dist else f"not read: not installed on {HERE}"
        purpose = need.get(name, "running")
        if name in marker:
            purpose += f"; only where `{marker[name]}`"
        used = "yes" if norm(name) in in_process else "no"
        rows.append(f"| {name} | {version} | {text.replace('|', '/')} | {purpose} | {used} |")
    if stale:
        sys.exit(
            "the environment doesn't match uv.lock (run `uv sync --offline`): " + "; ".join(stale)
        )
    return HEAD + "\n".join(rows) + "\n"


def main() -> int:
    text = page()
    if sys.argv[1:] == ["--check"]:
        if PAGE.exists() and PAGE.read_text() == text:
            return 0
        print(f"{PAGE.relative_to(ROOT)} is stale: run scripts/licence_table.py", file=sys.stderr)
        return 1
    PAGE.write_text(text)
    print(f"wrote {PAGE.relative_to(ROOT)} ({text.count(chr(10)) - HEAD.count(chr(10))} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
